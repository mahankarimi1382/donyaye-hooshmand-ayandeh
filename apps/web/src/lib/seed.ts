function nameSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9\u0600-\u06FF]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

function rfqLine(
  description: string,
  quantity: string,
  unit: RfqLineItem['unit'],
  productId: string,
  targetPrice: string,
  specifications?: string,
): RfqLineItem {
  return {
    description,
    quantity,
    unit,
    specifications,
    targetPrice,
    productId,
  };
}

function quoteLine(
  description: string,
  quantity: string,
  unit: QuoteLineItem['unit'],
  unitPrice: string,
  productId: string,
  hsCode: string,
  discountPercentage = 0,
): QuoteLineItem {
  const lineTotal = calculateLineTotal({unitPrice, quantity, discountPct: discountPercentage}, 'USD').format();
  return {
    description,
    quantity,
    unit,
    unitPrice,
    lineTotal,
    hsCode,
    discountPercentage,
    productId,
  };
}

function quoteFinancials(lines: readonly QuoteLineItem[], shipping: string, insurance: string, tax: string) {
  const inputs = lines.map((line) => ({
    unitPrice: line.unitPrice,
    quantity: line.quantity,
    discountPct: line.discountPercentage,
  }));
  const subtotal = calculateQuoteSubtotal(inputs, 'USD');
  const discountPct = lines[0]?.discountPercentage ?? 0;
  const discount = discountPct > 0 ? subtotal.mul(String(discountPct)).div('100') : Money.zero('USD');
  const total = calculateQuoteTotal({lines: inputs, shipping, insurance, tax, discount, currency: 'USD'});
  return {
    subtotal: subtotal.format(),
    discountAmount: discount.format(),
    total: total.format(),
    approvalRequired: requiresManagementApproval(discountPct, Number(total.format())),
  };
}

