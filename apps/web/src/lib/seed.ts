function buildSeedQuote(spec: SeedQuoteSpec, rfq: RfqRecord): QuoteRecord {
  const financials = quoteFinancials(spec.lines, spec.shippingAmount, spec.insuranceAmount, spec.taxAmount);
  const quote: QuoteRecord = {
    id: spec.id,
    quoteNumber: spec.quoteNumber,
    rfqId: spec.rfqId,
    status: spec.status,
    version: spec.version,
    sellerOrganizationId: SELLER_ORG_ID,
    buyerOrganizationId: spec.buyerOrganizationId,
    createdById: spec.createdById,
    assignedToUserId: spec.assignedToUserId,
    createdAt: spec.createdAt,
    updatedAt: spec.updatedAt,
    currency: 'USD',
    lines: spec.lines,
    shippingAmount: spec.shippingAmount,
    insuranceAmount: spec.insuranceAmount,
    taxAmount: spec.taxAmount,
    discountPercentage: spec.lines[0]?.discountPercentage ?? 0,
    subtotal: financials.subtotal,
    discountAmount: financials.discountAmount,
    total: financials.total,
    approvalRequired: financials.approvalRequired,
    incoterm: spec.incoterm,
    incotermNamedPlace: spec.incotermNamedPlace,
    paymentTerms: spec.paymentTerms,
    leadTimeDays: spec.leadTimeDays,
    productionDays: spec.productionDays,
    transitDays: spec.transitDays,
    validUntil: spec.validUntil,
    approvedByUserId: spec.approvedByUserId,
    approvalNote: spec.approvalNote,
    dispatchedAt: spec.dispatchedAt,
    acceptance: spec.acceptance,
    notes: spec.notes,
  };

  if (spec.snapshotAt && spec.dispatchedAt) {
    quote.snapshot = createQuoteSnapshot(
      {
        quoteId: quote.id,
        quoteNumber: quote.quoteNumber,
        rfqId: quote.rfqId,
        rfqReference: rfq.reference,
        version: quote.version,
        seller: {
          organizationId: SELLER_ORG_ID,
          name: 'Karvan International Trading Co. Ltd.',
          country: 'IR',
          city: 'Tehran',
          email: 'desk@karvan.trade',
        },
        buyer: {
          organizationId: quote.buyerOrganizationId,
          name: rfq.company.name,
          country: rfq.company.country,
          city: rfq.company.city,
          contactName: rfq.contact.name,
          email: rfq.contact.email,
        },
        lines: quote.lines.map((line, index) => ({
          id: `line_${index + 1}`,
          productId: line.productId,
          description: line.description,
          hsCode: line.hsCode,
          unit: line.unit,
          quantity: Number(line.quantity),
          unitPrice: line.unitPrice,
          discountPct: line.discountPercentage,
          lineTotal: line.lineTotal,
        })),
        financials: {
          currency: 'USD',
          subtotal: quote.subtotal,
          shipping: quote.shippingAmount,
          insurance: quote.insuranceAmount,
          tax: quote.taxAmount,
          discount: quote.discountAmount,
          total: quote.total,
        },
        incoterms: {code: quote.incoterm, location: quote.incotermNamedPlace ?? ''},
        leadTime: {
          productionDays: quote.productionDays,
          transitDays: quote.transitDays,
          totalDays: quote.leadTimeDays,
        },
        validUntil: quote.validUntil,
      },
      {createdAt: spec.snapshotAt},
    );
  }

  return quote;
}

